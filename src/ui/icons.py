def get_svg_pixmap(name: str, color: str = "#FFFFFF", size: int = 18) -> QPixmap:
    """Renders a named SVG into a crisp QPixmap with the requested color and size."""
    svg_raw = ICONS_SVG.get(name)
    if not svg_raw:
        pix = QPixmap(size, size)
        pix.fill(Qt.GlobalColor.transparent)
        return pix

    svg_colored = svg_raw.replace("currentColor", color)
    renderer = QSvgRenderer(QByteArray(svg_colored.encode("utf-8")))

    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pixmap)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter)
    painter.end()
    return pixmap


def get_svg_icon(name: str, color: str = "#FFFFFF", size: int = 18) -> QIcon:
    """Returns a QIcon for a given SVG name, color, and size."""
    return QIcon(get_svg_pixmap(name, color, size))
